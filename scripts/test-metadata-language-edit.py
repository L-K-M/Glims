#!/usr/bin/env python3
"""Build/run the public-header-only LangAlt single-language edit/Undo/refusal harness.

The committed known-map XCF is generated by make-metadata-language-fixture.py.
No GIMP headers or private symbols enter this harness. Use a141-slot adapter.
"""
import argparse
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
sub = parser.add_subparsers(dest="command", required=True)
build = sub.add_parser("build", help="strictly compile only")
build.add_argument("--out", type=Path, default=ROOT / ".build/metadata-language-edit-public-tests")
run = sub.add_parser("run", help="run with private settings and a bounded timeout")
run.add_argument("--binary", type=Path, default=ROOT / ".build/metadata-language-edit-public-tests")
run.add_argument("--library", type=Path, required=True)
run.add_argument("--fixture", type=Path, default=ROOT / "Engine/tests/fixtures/metadata-language.xcf")
run.add_argument("--work", type=Path, required=True)
args = parser.parse_args()
if args.command == "build":
    args.out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["xcrun", "clang", "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror",
                    "-I", str(ROOT / "Sources/CGlimsEngine/include"),
                    str(ROOT / "Engine/tests/metadata-language-edit-public-tests.c"), "-o", str(args.out)], check=True)
else:
    work = args.work.resolve()
    for name in ("home", "cache", "user"):
        (work / name).mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    env.update(HOME=str(work / "home"), XDG_CACHE_HOME=str(work / "cache"),
               GIMP3_DIRECTORY=str(work / "user"), G_DEBUG="fatal-criticals")
    subprocess.run([str(args.binary.resolve()), str(args.library.resolve()), str(args.fixture.resolve()), str(work)],
                   env=env, check=True, timeout=120)
